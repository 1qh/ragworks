/** Turn a born-digital page into a SCAN: rasterize it, rotate it slightly off-square, blur it, speckle it,
 * compress it as JPEG, and re-embed it with a text layer of exactly one character.
 *
 * That last character is deliberate and load-bearing. A PDF with NO text layer is trivially recognised as
 * needing OCR; a PDF with one character has a text layer that a text-layer parser will happily "succeed"
 * against, returning nothing useful while reporting success. The extraction shapes are DEFINED by that
 * number — one character against a 2,738-character born-digital control — so a stack that answers them is
 * reading pixels and one that does not is trusting a text layer that is not there.
 *
 * The noise is seeded and generated by an explicit LCG rather than a global random source: a benchmark
 * generator that produces a different page on every run is not reproducible, and two people running the
 * corpus would be measuring two different documents while comparing scores. */
import { ColorSpace, Document, Font, Image, Matrix, PDFDocument } from 'mupdf'
import sharp from 'sharp'

const DPI = 150
const WIDTH = 595
const HEIGHT = 842
/** A linear congruential generator, so the speckle is identical on every machine and every run. The
 * constants are the Numerical Recipes ones; the only property needed here is determinism. */
const lcg = (seed: number): (() => number) => {
  let state = Math.trunc(seed)
  return () => {
    state = Math.trunc(Math.imul(state, 1_664_525) + 1_013_904_223)
    return state / 0x1_00_00_00_00
  }
}
/** Speckle a greyscale raster in place. Pillow's version perturbs 2% of pixels by up to +/-45 levels, and
 * this reproduces that rather than inventing a new degradation — the shapes were measured against it. */
const speckle = (pixels: Buffer, seed: number): Buffer => {
  const rand = lcg(seed)
  const count = Math.floor(pixels.length * 0.02)
  for (let i = 0; i < count; i += 1) {
    const at = Math.floor(rand() * pixels.length)
    const delta = Math.floor(rand() * 91) - 45
    pixels[at] = Math.max(0, Math.min(255, (pixels[at] ?? 0) + delta))
  }
  return pixels
}
/** Degrade any raster (a rasterized PDF page, or an SVG rendered by sharp) into a scan. Both entry points
 * share this so the degradation is defined once — two copies would drift, and a shape measured against one
 * of them would silently stop matching the other. */
const scanifyImage = async (raster: Buffer, seed = 7): Promise<Uint8Array> => {
  const rotated = await sharp(raster)
    .greyscale()
    .rotate(0.4, { background: '#fcfcfc' })
    .blur(0.6)
    .raw()
    .toBuffer({ resolveWithObject: true })
  const jpeg = await sharp(speckle(rotated.data, seed), {
    raw: { channels: rotated.info.channels, height: rotated.info.height, width: rotated.info.width }
  })
    .jpeg({ quality: 72 })
    .toBuffer()
  const doc = new PDFDocument()
  const image = doc.addImage(new Image(new Uint8Array(jpeg)))
  const resources = doc.addObject({
    Font: { FR: doc.addSimpleFont(new Font('Helvetica')) },
    XObject: { Im0: image }
  })
  /** The single character is drawn in white at 1pt so it is invisible to a reader and present to a parser. */
  const content = `q ${String(WIDTH)} 0 0 ${String(HEIGHT)} 0 0 cm /Im0 Do Q\nBT /FR 1 Tf 1 1 1 rg 10 832 Td (.) Tj ET`
  doc.insertPage(-1, doc.addPage([0, 0, WIDTH, HEIGHT], 0, resources, content))
  /** Same wasm-view hazard as the page builder: copy out before another document is allocated. */
  return new Uint8Array(doc.saveToBuffer('').asUint8Array())
}
/** Render a born-digital PDF's first page and degrade it. */
// eslint-disable-next-line @typescript-eslint/promise-function-async -- rasterizing is synchronous and this only DELEGATES the awaiting to scanifyImage; marking it async makes the body awaitless, which biome's useAwait then fails, so the two rules oscillate and the fixer leaves whichever ran last
const scanify = (born: Uint8Array, seed = 7): Promise<Uint8Array> => {
  const source = Document.openDocument(born, 'application/pdf').loadPage(0)
  const raster = source.toPixmap(Matrix.scale(DPI / 72, DPI / 72), ColorSpace.DeviceGray, false, true)
  return scanifyImage(Buffer.from(raster.asPNG()), seed)
}
export { scanify, scanifyImage }
